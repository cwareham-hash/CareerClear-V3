#!/usr/bin/env node
// scripts/build-audio-durations.mjs
//
// Writes lib/audioDurations.ts: the narration length, in seconds, of every
// simulation block that has audio (every tier, every simulation), keyed by the
// block's frozen id. The app reads that file at build time to show real time
// estimates (the hub tier totals and each block's "9 min" label), so it never
// asks for durations at runtime.
//
// Usage:  node scripts/build-audio-durations.mjs
//
// Re-run it, and commit the regenerated lib/audioDurations.ts, whenever audio is
// generated or regenerated with scripts/generate-block-audio.mjs.
//
// Source: the local files in audio-samples/ (gitignored), the same ones uploaded
// to the block-audio bucket. Each block's length comes from the totalSeconds in
// its timestamps file (audio-samples/<block-id>.json); if that file is missing,
// the mp3 itself is measured with ffprobe. Block ids are read from the content
// files in lib/content/, so stray files in audio-samples/ are never picked up.

import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const CONTENT_DIR = path.join(ROOT, 'lib', 'content')
const AUDIO_DIR = path.join(ROOT, 'audio-samples')
const OUT_FILE = path.join(ROOT, 'lib', 'audioDurations.ts')

function fail(msg) {
  console.error(`STOP: ${msg}`)
  process.exit(1)
}

function probeDuration(file) {
  const out = execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', file])
  return parseFloat(out.toString().trim())
}

// Every block id in the content files ('<block-id>': { ... } at the top level).
const blockIds = []
for (const f of readdirSync(CONTENT_DIR).filter((f) => f.endsWith('.ts')).sort()) {
  const src = readFileSync(path.join(CONTENT_DIR, f), 'utf8')
  for (const m of src.matchAll(/^ {2}'([a-z0-9-]+)':\s*\{/gm)) blockIds.push(m[1])
}

const durations = {}
let fromJson = 0
let fromMp3 = 0
for (const id of [...new Set(blockIds)].sort()) {
  const json = path.join(AUDIO_DIR, `${id}.json`)
  const mp3 = path.join(AUDIO_DIR, `${id}.mp3`)
  let seconds = null
  if (existsSync(json)) {
    seconds = JSON.parse(readFileSync(json, 'utf8')).totalSeconds
    fromJson += 1
  } else if (existsSync(mp3)) {
    seconds = probeDuration(mp3)
    fromMp3 += 1
  } else {
    continue // no audio for this block
  }
  if (!Number.isFinite(seconds) || seconds <= 0) fail(`Block "${id}" has an unreadable duration (${seconds}).`)
  durations[id] = Math.round(seconds * 100) / 100
}

const ids = Object.keys(durations)
if (ids.length === 0) fail('No block audio found in audio-samples/. Nothing written.')

const lines = [
  '// lib/audioDurations.ts — GENERATED FILE, do not edit by hand.',
  '//',
  '// Narration length in seconds for every simulation block that has audio, keyed',
  '// by frozen block id. Read at build time for the hub tier totals and the',
  '// per-block time labels (see lib/audioTime.ts).',
  '//',
  '// Generated by scripts/build-audio-durations.mjs from the local audio files in',
  '// audio-samples/. Whenever audio is generated or regenerated, re-run',
  '//   node scripts/build-audio-durations.mjs',
  '// and commit the result.',
  '',
  `// ${ids.length} blocks with audio.`,
  'export const AUDIO_DURATIONS: Record<string, number> = {',
  ...ids.map((id) => `  '${id}': ${durations[id]},`),
  '}',
  '',
]
writeFileSync(OUT_FILE, lines.join('\n'))

const total = ids.reduce((n, id) => n + durations[id], 0)
console.log(`Wrote ${path.relative(ROOT, OUT_FILE)}: ${ids.length} blocks (${fromJson} from timestamps files, ${fromMp3} measured from mp3), ${(total / 3600).toFixed(2)} hours in total.`)
